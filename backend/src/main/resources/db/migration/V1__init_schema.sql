-- 처음 스키마 (PostgreSQL). MySQL 시절의 V1~V3(공지·회원·공지 본문)을 PostgreSQL 문법으로 합쳐 다시 시작했다.
-- 이 파일부터는 머지된 뒤 고치지 않고 V2부터 새 버전을 추가한다.
-- H2(PostgreSQL 모드)와 PostgreSQL에서 모두 돌도록 DB 전용 문법(SERIAL, 배열, JSONB 등)을 쓰지 않는다

-- 회원. 모든 사용자별 학습 데이터는 users.id를 외래 키로 가진다 (docs/backend-design.md)
CREATE TABLE users (
    id                       BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    -- 소문자로 바꿔 저장한다. 중복 가입은 애플리케이션 검사와 이 UNIQUE 제약으로 함께 막는다
    email                    VARCHAR(254) NOT NULL,
    -- BCrypt 해시 (원본 비밀번호는 저장하지 않는다)
    password_hash            VARCHAR(100) NOT NULL,
    name                     VARCHAR(30)  NOT NULL,
    role                     VARCHAR(20)  NOT NULL,
    -- AI 대화 분석 동의(선택). 철회하면 가져온 대화와 분석 결과를 함께 삭제한다
    ai_analysis_consent      BOOLEAN      NOT NULL,
    ai_analysis_consented_at TIMESTAMP(6) NULL,
    terms_agreed_at          TIMESTAMP(6) NOT NULL,
    privacy_agreed_at        TIMESTAMP(6) NOT NULL,
    created_at               TIMESTAMP(6) NOT NULL,
    updated_at               TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- 로그인 세션별 Refresh Token. 원문은 저장하지 않고 SHA-256 해시만 저장한다.
-- 갱신할 때마다 새 행을 만들고 이전 행은 revoked_at을 채운다 (토큰 회전).
-- 이미 폐기된 토큰이 다시 오면 같은 session_id의 행을 모두 폐기한다 (재사용 감지)
CREATE TABLE refresh_token (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT       NOT NULL,
    session_id VARCHAR(36)  NOT NULL,
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    revoked_at TIMESTAMP(6) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    -- 탈퇴하면 세션도 함께 지운다
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_token_session ON refresh_token (session_id);
CREATE INDEX idx_refresh_token_user ON refresh_token (user_id);

-- 공지사항. 본문은 글자만 저장한다 (HTML·마크다운으로 해석하지 않는다).
-- 본문·수정 시각은 비워 둘 수 있게 하고, 작성·수정할 때는 API가 제목과 본문을 모두 요구한다.
-- TEXT 대신 VARCHAR로 둔 것은 Hibernate 검증(ddl-auto: validate)이 H2와 PostgreSQL에서 같게 통과하게 하기 위해서다
CREATE TABLE notice (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    title      VARCHAR(100) NOT NULL,
    content    VARCHAR(5000),
    created_at DATE         NOT NULL,
    updated_at TIMESTAMP(6),
    -- 작성한 관리자가 탈퇴해도 공지는 남는다
    author_id  BIGINT,
    PRIMARY KEY (id),
    CONSTRAINT fk_notice_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_notice_created_at ON notice (created_at);
